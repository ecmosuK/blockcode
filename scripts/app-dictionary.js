const CODE_DICTIONARY_INDEX = [];
CODE_DICTIONARY_GROUPS.forEach((group) => {
  group.entries.forEach((entry) => {
    const aliases = (entry.aliases || []).join(' ');
    const definition = entry.definition || '';
    const example = entry.example || '';
    CODE_DICTIONARY_INDEX.push({
      group: group,
      entry: entry,
      groupText: group.name.toLowerCase(),
      aliasesText: aliases.toLowerCase(),
      definitionText: definition.toLowerCase(),
      exampleText: example.toLowerCase(),
      searchText: [entry.term, group.name, entry.kind, definition, example, aliases]
        .filter(Boolean).join(' ').toLowerCase()
    });
  });
});

const CODE_DICTIONARY_TOTAL = CODE_DICTIONARY_INDEX.length;
let codeDictionaryInitialized = false;

function codeDictionaryMatchScore(item, tokens) {
  const term = item.entry.term.toLowerCase();
  let score = 0;
  tokens.forEach((token) => {
    if (term === token) score += 120;
    else if (term.startsWith(token)) score += 60;
    else if (term.includes(token)) score += 35;
    else if (item.aliasesText.includes(token)) score += 18;
    else if (item.groupText.includes(token)) score += 8;
    else if (item.definitionText.includes(token) || item.exampleText.includes(token)) score += 2;
  });
  return score;
}

function codeDictionaryTypingTarget(target) {
  return Boolean(target && target.closest &&
    target.closest('input, textarea, select, [contenteditable], [role="textbox"]'));
}

function codeDictionaryPlural(count) {
  return count === 1 ? 'term' : 'terms';
}

function renderCodeDictionary(query) {
  const results = document.getElementById('dictionaryResults');
  const count = document.getElementById('dictionaryCount');
  if (!results || !count) return;

  const tokens = String(query || '').toLowerCase().trim().split(/\s+/).filter(Boolean);
  const matchedItems = tokens.length
    ? CODE_DICTIONARY_INDEX
      .filter((item) => tokens.every((token) => item.searchText.includes(token)))
      .map((item) => ({ item: item, score: codeDictionaryMatchScore(item, tokens) }))
      .sort((a, b) => b.score - a.score ||
        a.item.entry.term.length - b.item.entry.term.length)
    : CODE_DICTIONARY_INDEX.map((item) => ({ item: item, score: 0 }));

  results.replaceChildren();
  count.textContent = tokens.length
    ? matchedItems.length + ' of ' + CODE_DICTIONARY_TOTAL + ' ' + codeDictionaryPlural(CODE_DICTIONARY_TOTAL)
    : CODE_DICTIONARY_TOTAL + ' ' + codeDictionaryPlural(CODE_DICTIONARY_TOTAL);

  if (!matchedItems.length) {
    const empty = document.createElement('div');
    empty.className = 'dictionary-empty';
    const title = document.createElement('h3');
    title.textContent = 'No matching terms';
    const text = document.createElement('p');
    text.textContent = 'Nothing matched "' + String(query).trim() + '". Try a shorter word such as float, list, sprite, LZ4, or build.';
    const clear = document.createElement('button');
    clear.type = 'button';
    clear.className = 'btn btn-small';
    clear.textContent = 'Clear search';
    clear.addEventListener('click', () => {
      const search = document.getElementById('dictionarySearch');
      if (!search) return;
      search.value = '';
      renderCodeDictionary('');
      search.focus();
    });
    empty.append(title, text, clear);
    results.appendChild(empty);
    return;
  }

  const groups = new Map();
  const groupScores = new Map();
  matchedItems.forEach((result) => {
    const item = result.item;
    if (!groups.has(item.group)) {
      groups.set(item.group, []);
      groupScores.set(item.group, 0);
    }
    groups.get(item.group).push(item.entry);
    groupScores.set(item.group, Math.max(groupScores.get(item.group), result.score));
  });

  const orderedGroups = CODE_DICTIONARY_GROUPS.filter((group) => groups.has(group));
  orderedGroups.sort((a, b) => groupScores.get(b) - groupScores.get(a) ||
    CODE_DICTIONARY_GROUPS.indexOf(a) - CODE_DICTIONARY_GROUPS.indexOf(b));

  const fragment = document.createDocumentFragment();
  orderedGroups.forEach((group) => {
    const entries = groups.get(group);
    const groupIndex = CODE_DICTIONARY_GROUPS.indexOf(group);
    const section = document.createElement('section');
    section.className = 'dictionary-group';
    section.setAttribute('aria-labelledby', 'dictionaryGroup' + groupIndex);

    const head = document.createElement('div');
    head.className = 'dictionary-group-head';
    const title = document.createElement('h3');
    title.id = 'dictionaryGroup' + groupIndex;
    title.textContent = group.name;
    const groupCount = document.createElement('span');
    groupCount.className = 'dictionary-group-count';
    groupCount.textContent = entries.length + ' ' + codeDictionaryPlural(entries.length);
    head.append(title, groupCount);

    const description = document.createElement('p');
    description.className = 'dictionary-group-note';
    description.textContent = group.description;

    const list = document.createElement('div');
    list.className = 'dictionary-list';
    entries.forEach((entry) => {
      const article = document.createElement('article');
      article.className = 'dictionary-entry';

      const entryHead = document.createElement('div');
      entryHead.className = 'dictionary-entry-head';
      const term = document.createElement('code');
      term.className = 'dictionary-term';
      term.textContent = entry.term;
      const kind = document.createElement('span');
      kind.className = 'dictionary-kind';
      kind.textContent = entry.kind || 'term';
      entryHead.append(term, kind);

      const definition = document.createElement('p');
      definition.className = 'dictionary-definition';
      definition.textContent = entry.definition;

      article.append(entryHead, definition);
      if (entry.example) {
        const example = document.createElement('code');
        example.className = 'dictionary-example';
        example.textContent = entry.example;
        article.appendChild(example);
      }
      list.appendChild(article);
    });

    section.append(head, description, list);
    fragment.appendChild(section);
  });

  results.appendChild(fragment);
}

function openCodeDictionary(focusSearch) {
  const dialog = document.getElementById('codeDictionary');
  const search = document.getElementById('dictionarySearch');
  if (!dialog) return;
  if (!dialog.open) {
    if (search) search.value = '';
    renderCodeDictionary('');
    dialog.showModal();
  }
  if (focusSearch && search) {
    search.focus();
    search.select();
  } else {
    dialog.focus();
  }
}

function initCodeDictionary() {
  if (codeDictionaryInitialized) return;
  const openButton = document.getElementById('dictionaryBtn');
  const dialog = document.getElementById('codeDictionary');
  const closeButton = document.getElementById('dictionaryClose');
  const search = document.getElementById('dictionarySearch');
  if (!openButton || !dialog || !closeButton || !search) return;

  codeDictionaryInitialized = true;
  renderCodeDictionary('');

  openButton.addEventListener('click', () => openCodeDictionary(true));
  closeButton.addEventListener('click', () => dialog.close());
  search.addEventListener('input', () => renderCodeDictionary(search.value));

  dialog.addEventListener('click', (event) => {
    if (event.target === dialog) dialog.close();
  });

  document.addEventListener('keydown', (event) => {
    if (event.defaultPrevented || event.repeat || event.isComposing) return;
    if (String(event.key).toLowerCase() !== 'f') return;
    if (event.ctrlKey || event.metaKey || event.altKey || event.shiftKey) return;
    if (codeDictionaryTypingTarget(event.target) ||
        codeDictionaryTypingTarget(document.activeElement)) return;
    event.preventDefault();
    if (dialog.open) {
      dialog.close();
    } else {
      openCodeDictionary(false);
    }
  });
}
