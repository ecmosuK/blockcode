import fs from 'node:fs';
import { test, expect } from './fixtures';
import { BlockCodePage } from './pages/BlockCodePage';

test.describe('Block workspace editing', () => {
  test('drag a hat block onto the canvas and snap a say block underneath', async ({ page }, testInfo) => {
    const app = new BlockCodePage(page);

    await app.openEditor();
    await app.clearWorkspace();
    await expect(app.workspaceBlocks).toHaveCount(0);

    const canvas = await app.canvas.boundingBox();
    if (!canvas) throw new Error('Workspace canvas is not visible');

    await app.dragPaletteBlockTo('start', canvas.x + 120, canvas.y + 100);
    await expect(app.workspaceBlocks).toHaveCount(1);
    await expect(app.workspaceBlocks.first()).toHaveAttribute('data-type', 'start');

    await app.capture(testInfo, 'drag-hat-block.png');

    const startBlock = app.workspaceBlocks.first();
    await app.dragPaletteBlockBelow('say', startBlock);

    await expect(app.scripts).toHaveCount(1);
    await expect(app.workspaceBlocks).toHaveCount(2);
    expect(await app.workspaceBlockTypes()).toEqual(['start', 'say']);
    expect(await app.workspaceBlocks.evaluateAll((elements) =>
      elements.map((element) => (element as HTMLElement).dataset.path)
    )).toEqual(['0.0', '0.1']);

    await expect(app.watchCode).toContainText(/watch_say\("Hello, NASA!",\s*1\.0f\)/);

    await app.capture(testInfo, 'snapped-say-block.png');
  });

  test('Delete removes the selected block from the workspace', async ({ page }) => {
    const app = new BlockCodePage(page);

    await app.openEditor();
    await app.loadStarterWorkspace();
    await expect(app.workspaceBlocks).toHaveCount(6);

    // Double-click isolates a single block; a single click selects the whole
    // stack from that point down.
    await app.workspaceBlocks.first().dblclick({ position: { x: 8, y: 8 } });
    await expect(app.workspaceBlocks.first()).toHaveClass(/is-selected/);

    await page.keyboard.press('Delete');

    await expect(app.workspaceBlocks).toHaveCount(5);
    await expect(app.toast).toHaveText('1 block deleted.');
  });

  test('Download .cpp produces a complete generated watch app', async ({ page }, testInfo) => {
    const app = new BlockCodePage(page);

    await app.openEditor();
    await app.loadStarterWorkspace();

    const download = await app.downloadCpp();
    expect(download.suggestedFilename()).toBe('blockcode-app.cpp');

    const outputPath = testInfo.outputPath('blockcode-app.cpp');
    await download.saveAs(outputPath);
    const source = fs.readFileSync(outputPath, 'utf8');

    expect(source).toContain('// Generated by BlockCode.');
    expect(source).toContain('#include <math.h>');
    expect(source).toContain('watch_say("Hello, NASA!", 1.2f)');
    expect(source.length).toBeGreaterThan(10_000);

    await expect(app.toast).toHaveText('Downloaded blockcode-app.cpp.');
  });
});
